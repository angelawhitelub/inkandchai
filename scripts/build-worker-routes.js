#!/usr/bin/env node
/**
 * Generates worker/routes.generated.js — a static require() for every function
 * handler. Workers cannot require() a dynamic path, so the route table has to
 * be materialised at build time rather than resolved per request.
 *
 * Also emits the scheduled-job table by parsing jobs.toml, so the cron
 * schedules stay defined in exactly one place.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const FN_DIR = path.join(ROOT, 'netlify', 'functions');
const OUT = path.join(ROOT, 'worker', 'routes.generated.js');

const handlers = fs.readdirSync(FN_DIR)
  .filter((f) => f.endsWith('.js') && !f.endsWith('.test.js'))
  .map((f) => f.replace(/\.js$/, ''))
  .sort();

// Netlify accepts the @hourly/@daily aliases; Cloudflare cron triggers do not.
const CRON_ALIASES = {
  '@hourly': '0 * * * *',
  '@daily': '0 0 * * *',
  '@midnight': '0 0 * * *',
  '@weekly': '0 0 * * 0',
  '@monthly': '0 0 1 * *',
  '@yearly': '0 0 1 1 *',
  '@annually': '0 0 1 1 *',
};

const toml = fs.readFileSync(path.join(ROOT, 'jobs.toml'), 'utf8');
const schedules = {};
// Parse a comment-stripped copy. A comment between the header and its schedule
// line used to break this match silently: the job vanished from the schedule
// table, kept its HTTP route, and simply never ran again. Stripping first also
// stops the format examples in this file's own header comment from parsing as
// real jobs.
const bare = toml.replace(/^[^\S\n]*#[^\n]*$/gm, '');
const re = /\[functions\."([^"]+)"\]\s*\n\s*schedule\s*=\s*"([^"]+)"/g;
let m;
while ((m = re.exec(bare))) {
  const raw = m[2].trim();
  schedules[m[1]] = CRON_ALIASES[raw] || raw;
}

// Every block that declares a schedule must have been parsed into one. A job
// that declares a cron and does not reach the table keeps working as an HTTP
// route, so nothing breaks loudly — it just stops running.
const declared = [...bare.matchAll(/\[functions\."([^"]+)"\]([\s\S]*?)(?=\n\[|$)/g)]
  .filter(([, , bodyText]) => /^[^\S\n]*schedule\s*=/m.test(bodyText))
  .map(([, jobName]) => jobName);
const dropped = declared.filter((n) => !(n in schedules));
if (dropped.length) {
  console.error(`[worker-routes] declared a schedule but did not parse into the table: ${dropped.join(', ')}`);
  process.exit(1);
}

// A cron the Worker is never asked to run is a job that silently does not
// exist. phonepe-payment-sweep-scheduled sat on "*/10 * * * *" — absent from
// [triggers] — and never ran once. Nothing failed, so nothing said so.
const wranglerToml = fs.readFileSync(path.join(ROOT, 'wrangler.toml'), 'utf8');
const cronsBlock = /crons\s*=\s*\[([\s\S]*?)\]/.exec(wranglerToml);
const triggers = new Set(cronsBlock ? [...cronsBlock[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]) : []);
const unfired = Object.entries(schedules).filter(([, cron]) => !triggers.has(cron));
if (unfired.length) {
  for (const [name, cron] of unfired) {
    console.error(`[worker-routes] "${name}" is scheduled on "${cron}", which is not in wrangler.toml [triggers] — it will never run`);
  }
  process.exit(1);
}

const missing = Object.keys(schedules).filter((n) => !handlers.includes(n));
if (missing.length) {
  console.error(`[worker-routes] scheduled but no handler file: ${missing.join(', ')}`);
  process.exit(1);
}

const lines = [
  '// GENERATED by scripts/build-worker-routes.js — do not edit.',
  `// ${handlers.length} handlers, ${Object.keys(schedules).length} scheduled.`,
  '',
  'const routes = {',
  ...handlers.map((h) => `  ${JSON.stringify(h)}: require(${JSON.stringify(`../netlify/functions/${h}.js`)}),`),
  '};',
  '',
  `const schedules = ${JSON.stringify(schedules, null, 2)};`,
  '',
  'module.exports = { routes, schedules };',
  '',
];

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join('\n'));

// Several handlers share a cron expression; the Worker fans one trigger out to
// every handler registered against it, so wrangler only needs the distinct set.
const crons = [...new Set(Object.values(schedules))].sort();
fs.writeFileSync(path.join(ROOT, 'worker', 'crons.generated.json'), JSON.stringify(crons, null, 2) + '\n');

console.log(`[worker-routes] ${handlers.length} handlers, ${Object.keys(schedules).length} scheduled jobs on ${crons.length} distinct triggers`);
console.log(`[worker-routes] crons: ${crons.join(' | ')}`);

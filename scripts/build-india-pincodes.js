/**
 * Generates data/india-pincodes.generated.js from India Post's "All India
 * Pincode Directory" (data.gov.in, one row per post office).
 *
 *   node scripts/build-india-pincodes.js pincode.csv
 *
 * Source: https://www.data.gov.in/resource/all-india-pincode-directory-till-last-month
 * (mirrored as pincode.csv in github.com/dropdevrahul/pincodes-india).
 *
 * Only the set of pincodes is kept -- it answers "is this six-digit number a
 * pincode at all, or a flat number?" (see utils/india-pincodes). Same format
 * as the Delhivery list: one sorted, concatenated string of 6-digit codes.
 */
const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/build-india-pincodes.js <pincode.csv>');
  process.exit(1);
}

// Fields are quoted and office names can carry commas.
function parseLine(line) {
  const out = [];
  let cur = '', quoted = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (quoted) {
      if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; }
      else if (ch === '"') quoted = false;
      else cur += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { out.push(cur); cur = ''; }
    else cur += ch;
  }
  out.push(cur);
  return out;
}

const lines = fs.readFileSync(src, 'utf8').split(/\r?\n/).filter(Boolean);
const header = parseLine(lines.shift()).map((s) => s.trim());
const iPin = header.indexOf('Pincode');
if (iPin === -1) throw new Error(`column "Pincode" missing from ${src} — header is: ${header.join(', ')}`);

const seen = new Set();
const skipped = [];
for (const line of lines) {
  const pin = String(parseLine(line)[iPin] || '').trim();
  if (!/^[1-8]\d{5}$/.test(pin)) { skipped.push(pin); continue; }
  seen.add(pin);
}
const pins = [...seen].sort();
if (pins.length < 15000) throw new Error(`only ${pins.length} pincodes read from ${src} — wrong file?`);

const out = `// GENERATED by scripts/build-india-pincodes.js — do not edit.
// Source: India Post "All India Pincode Directory" (data.gov.in).
// ${pins.length} pincodes from ${lines.length} post offices.
/* eslint-disable */
module.exports = {
  generatedAt: ${JSON.stringify(new Date().toISOString().slice(0, 10))},
  count: ${pins.length},
  // Sorted, concatenated 6-digit codes.
  pins: ${JSON.stringify(pins.join(''))},
};
`;
const dest = path.join(__dirname, '..', 'data', 'india-pincodes.generated.js');
fs.writeFileSync(dest, out);
console.log(`[india-pincodes] ${pins.length} pincodes from ${lines.length} post offices -> ${path.relative(process.cwd(), dest)}`);
if (skipped.length) console.log(`[india-pincodes] dropped ${skipped.length} rows without a valid pincode: ${skipped.slice(0, 10).join(', ')}`);

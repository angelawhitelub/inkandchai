/**
 * Generates data/delhivery-pincodes.generated.js from Delhivery's own
 * "Pincode Serviceability" CSV export.
 *
 *   node scripts/build-delhivery-pincodes.js ~/Downloads/"Pincode Serviceability.csv"
 *
 * The CSV is the authoritative list: a pincode that is NOT in it is one
 * Delhivery does not deliver to at all. Re-run this whenever they publish a
 * new export and commit the result -- it is bundled into the Worker, so a
 * refresh is a deploy, not a migration.
 *
 * FORMAT. 18,699 pincodes as one concatenated string of 6-digit codes rather
 * than a JSON array: same data, a third of the bytes, and it costs one slice()
 * per lookup instead of parsing 18,699 quoted strings on every cold start.
 * The exception lists are small enough to stay as plain arrays.
 */
const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/build-delhivery-pincodes.js <Pincode Serviceability.csv>');
  process.exit(1);
}

const text = fs.readFileSync(src, 'utf8');
const lines = text.split(/\r?\n/).filter(Boolean);
const header = lines.shift().split(',').map((s) => s.trim());
const col = (name) => {
  const i = header.indexOf(name);
  if (i === -1) throw new Error(`column "${name}" missing from ${src} — header is: ${header.join(', ')}`);
  return i;
};
const iPin = col('Pincode'), iCod = col('COD'), iRev = col('Reverse Pickup'), iRepl = col('REPL'), iCash = col('Cash');

const pins = [];
const skipped = [];
const noCod = [], noReverse = [], noRepl = [], noCash = [];
const seen = new Set();
for (const line of lines) {
  const f = line.split(',');
  const pin = String(f[iPin] || '').trim();
  // Real Indian pincodes are six digits starting 1-8. Delhivery's export
  // carries a handful of internal rows that are not ("100004", "98989x") and
  // they are the only rows flagged no-COD, which would otherwise read as a
  // genuine COD gap. Drop them here rather than teaching every caller about
  // them.
  if (!/^[1-8]\d{5}$/.test(pin)) { skipped.push(pin || String(f[iPin])); continue; }
  if (seen.has(pin)) continue;
  seen.add(pin);
  pins.push(pin);
  const yes = (v) => String(v || '').trim().toUpperCase() === 'Y';
  if (!yes(f[iCod]))  noCod.push(pin);
  if (!yes(f[iRev]))  noReverse.push(pin);
  if (!yes(f[iRepl])) noRepl.push(pin);
  if (!yes(f[iCash])) noCash.push(pin);
}
pins.sort();

const out = `// GENERATED by scripts/build-delhivery-pincodes.js — do not edit.
// Source: Delhivery "Pincode Serviceability" export.
// ${pins.length} serviceable pincodes. Anything absent is NOT serviceable.
/* eslint-disable */
module.exports = {
  generatedAt: ${JSON.stringify(new Date().toISOString().slice(0, 10))},
  count: ${pins.length},
  // Sorted, concatenated 6-digit codes.
  pins: ${JSON.stringify(pins.join(''))},
  noCod: ${JSON.stringify(noCod)},
  noReverse: ${JSON.stringify(noReverse)},
  noReplacement: ${JSON.stringify(noRepl)},
  noCash: ${JSON.stringify(noCash)},
};
`;
const dest = path.join(__dirname, '..', 'data', 'delhivery-pincodes.generated.js');
fs.writeFileSync(dest, out);
console.log(`[delhivery-pincodes] ${pins.length} pincodes -> ${path.relative(process.cwd(), dest)}`);
console.log(`[delhivery-pincodes] no COD: ${noCod.length}, no reverse pickup: ${noReverse.length}, no replacement: ${noRepl.length}, no cash: ${noCash.length}`);
if (skipped.length) console.log(`[delhivery-pincodes] dropped ${skipped.length} rows that are not valid Indian pincodes: ${skipped.join(', ')}`);
